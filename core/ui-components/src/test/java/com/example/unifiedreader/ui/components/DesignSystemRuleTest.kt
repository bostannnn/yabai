package com.example.unifiedreader.ui.components

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Keeps app and feature code on the design system (`docs/design/system/`).
 *
 * Literal dp values in paddings and corner radii are where margins drift, so they ratchet: each
 * file's count is written down in `src/test/design-baselines/`, a file may not gain any, and when
 * one loses some its line has to come down too. New code takes its numbers from [AppLayout], the
 * theme's radii and the kit's `*Defaults` objects. After removing literals, rewrite the baselines:
 *
 *     ./gradlew :core:ui-components:testDebugUnitTest -PupdateDesignBaselines
 */
class DesignSystemRuleTest {

    @Test
    fun `only content titles use AppScreenTitle`() {
        val root = repositoryRoot()
        val users = sourceFiles(root)
            .filter { file -> AppScreenTitleCall.containsMatchIn(file.readText()) }
            .map { file -> file.relativeTo(root).invariantSeparatorsPath }
            .filterNot { path -> AppScreenTitleAllowed.any(path::endsWith) }
        assertTrue(
            "AppScreenTitle is for a title that is the content (a series, a Kavita list, a first-launch " +
                "question), never a screen's own name: the rail or the drawer already says where you are " +
                "(docs/design/system/project/titles.md). Used in:\n" + users.joinToString("\n"),
            users.isEmpty(),
        )
    }

    @Test
    fun `no new literal dp paddings in app and feature code`() {
        assertRatchet(
            baseline = "literal-paddings.txt",
            what = "literal dp values in padding(...) and PaddingValues(...)",
            fix = "use AppLayout (appGutter(), inset, contentTop, ...) or the kit's *Defaults",
        ) { source -> literalDpInCalls(source, PaddingCall) }
    }

    @Test
    fun `no new literal corner radii in app and feature code`() {
        assertRatchet(
            baseline = "literal-corners.txt",
            what = "literal dp values in RoundedCornerShape(...)",
            fix = "use the theme's radii (cover, control, container) or the kit's *Defaults",
        ) { source -> literalDpInCalls(source, CornerCall) }
    }

    @Test
    fun `literal dp counting reads whole calls across lines`() {
        val source = """
            Modifier.padding(
                start = 20.dp,
                end = AppLayout.inset - 8.dp,
            ).padding(horizontal = gutter)
            PaddingValues(12.dp)
            RoundedCornerShape(6.dp)
            Modifier.windowInsetsPadding(insets).size(40.dp)
        """
        assertEquals(3, literalDpInCalls(source, PaddingCall))
        assertEquals(1, literalDpInCalls(source, CornerCall))
    }

    private fun assertRatchet(
        baseline: String,
        what: String,
        fix: String,
        count: (String) -> Int,
    ) {
        val root = repositoryRoot()
        val baselineFile = root.resolve(BaselineDir).resolve(baseline)
        val current = sourceFiles(root)
            .associate { file -> file.relativeTo(root).invariantSeparatorsPath to count(file.readText()) }
            .filterValues { it > 0 }
            .toSortedMap()
        if (System.getProperty("updateDesignBaselines") == "true") {
            baselineFile.parentFile.mkdirs()
            baselineFile.writeText(
                "# $what, per file. Generated by DesignSystemRuleTest; counts may only go down.\n" +
                    current.entries.joinToString("") { (path, n) -> "$n $path\n" },
            )
            return
        }
        val allowed = readBaseline(baselineFile)
        val grown = current.filter { (path, n) -> n > (allowed[path] ?: 0) }
            .map { (path, n) -> "$path: $n (baseline ${allowed[path] ?: 0})" }
        val shrunk = allowed.filter { (path, n) -> (current[path] ?: 0) < n }
            .map { (path, n) -> "$path: ${current[path] ?: 0} (baseline $n)" }
        assertTrue(
            "New $what, $fix:\n${grown.joinToString("\n")}",
            grown.isEmpty(),
        )
        assertTrue(
            "Fewer $what than the baseline: good. Lower it with " +
                "`./gradlew :core:ui-components:testDebugUnitTest -PupdateDesignBaselines`:\n${shrunk.joinToString("\n")}",
            shrunk.isEmpty(),
        )
    }

    private fun readBaseline(file: File): Map<String, Int> =
        if (!file.isFile) {
            emptyMap()
        } else {
            file.readLines()
                .map(String::trim)
                .filter { it.isNotEmpty() && !it.startsWith("#") }
                .associate { line -> line.substringAfter(' ') to line.substringBefore(' ').toInt() }
        }

    private fun sourceFiles(root: File): List<File> =
        (listOf(root.resolve("app/src/main")) +
            (root.resolve("feature").listFiles { file -> file.isDirectory }?.map { it.resolve("src/main") } ?: emptyList()))
            .filter { it.isDirectory }
            .flatMap { sourceRoot -> sourceRoot.walkTopDown().filter { it.isFile && it.extension == "kt" } }

    private fun repositoryRoot(): File {
        var dir: File? = File(System.getProperty("user.dir")).absoluteFile
        while (dir != null && !dir.resolve("settings.gradle.kts").isFile) dir = dir.parentFile
        return requireNotNull(dir) { "settings.gradle.kts not found above ${System.getProperty("user.dir")}" }
    }

    internal companion object {
        const val BaselineDir = "core/ui-components/src/test/design-baselines"

        val AppScreenTitleCall = Regex("""\bAppScreenTitle\(""")

        /** The series and Kavita list header, a list's name on its page, and first launch's questions. */
        val AppScreenTitleAllowed = listOf(
            "feature/library/LibraryHeader.kt",
            "feature/lists/UserListPage.kt",
            "feature/settings/SourceStartFlow.kt",
        )

        val PaddingCall = Regex("""\b(padding|PaddingValues)\(""")
        val CornerCall = Regex("""\bRoundedCornerShape\(""")
        private val LiteralDp = Regex("""(?<![\w.])\d+(\.\d+)?\.dp\b""")

        /** Literal `N.dp` values inside the arguments of every [call] in [source]. */
        fun literalDpInCalls(source: String, call: Regex): Int = call.findAll(source).sumOf { match ->
            val open = match.range.last
            var depth = 0
            var close = open
            while (close < source.length) {
                when (source[close]) {
                    '(' -> depth++
                    ')' -> if (--depth == 0) break
                }
                close++
            }
            LiteralDp.findAll(source.substring(open, minOf(close + 1, source.length))).count()
        }
    }
}
